import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";

/**
 * pi's `/reload` is an interactive-TUI command and RPC mode has no equivalent request, but pi
 * hands extension commands the session's own reload action. Loading this extension into every
 * session with `--extension` is what makes `/reload` reachable over RPC: pi runs the command from
 * a prompt and the RPC bridge calls `session.reload()` (the same call pi-web makes in-process).
 *
 * It is materialized from source rather than shipped as a path so the plugin keeps working when
 * Paseo loads it from a bundle.
 */
export const RELOAD_COMMAND_EXTENSION = `// Generated by paseo-pi (server/provider/reload-extension.ts). Do not edit.
export default function paseoReloadCommand(pi) {
	pi.registerCommand("reload", {
		description: "Reload pi settings, models, extensions, skills, prompts, themes and context files",
		handler: async (_args, ctx) => {
			await ctx.reload();
		},
	});
}
`;

const EXTENSION_DIRECTORY = "paseo-pi";
const DIGEST = createHash("sha256").update(RELOAD_COMMAND_EXTENSION).digest("hex").slice(0, 12);
const FILE_NAME = `reload-command-${DIGEST}.mjs`;

let cached: Promise<string> | undefined;

/** Absolute path of the generated extension, written once per process. */
export function reloadCommandExtensionPath(): Promise<string> {
	cached ??= materialize().catch((error) => {
		cached = undefined;
		throw error;
	});
	return cached;
}

async function materialize(): Promise<string> {
	const directory = join(tmpdir(), EXTENSION_DIRECTORY);
	await mkdir(directory, { recursive: true, mode: 0o700 });
	const path = join(directory, FILE_NAME);
	try {
		if ((await readFile(path, "utf8")) === RELOAD_COMMAND_EXTENSION) return path;
	} catch {
		// Missing or unreadable: write it below.
	}
	await writeFile(path, RELOAD_COMMAND_EXTENSION, { encoding: "utf8", mode: 0o600 });
	return path;
}

/** True for the prompt text that runs the generated command: `/reload` on its own. */
export function isReloadCommand(text: string): boolean {
	return text.trim() === "/reload";
}
