import { chmod, mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { PI_RELOAD_EXTENSION_FILE } from "../shared/constants";
import { RELOAD_COMMAND_EXTENSION } from "./provider/reload-extension";

const MARKER = "Generated by paseo-pi";

/** Absolute path of the reload extension installed for pi's built-in sessions. */
export function builtinReloadExtensionPath(agentDir: string): string {
	return join(agentDir, "extensions", PI_RELOAD_EXTENSION_FILE);
}

let queue: Promise<unknown> = Promise.resolve();

/**
 * Installs or removes the generated reload extension in pi's own extensions directory.
 * Built-in pi sessions discover it on start, so `/reload` works without a provider.
 *
 * Serialized because settings reads and subscriptions can fire together. A file without the
 * generated marker is never overwritten or deleted.
 */
export function ensureBuiltinReloadExtension(agentDir: string, enabled: boolean): Promise<boolean> {
	const run = queue.then(() => ensureNow(agentDir, enabled));
	queue = run.catch(() => undefined);
	return run;
}

async function ensureNow(agentDir: string, enabled: boolean): Promise<boolean> {
	const path = builtinReloadExtensionPath(agentDir);
	if (!enabled) {
		let current: string;
		try {
			current = await readFile(path, "utf8");
		} catch (error) {
			if ((error as { code?: string }).code === "ENOENT") return false;
			throw error;
		}
		if (!current.includes(MARKER)) return false;
		await rm(path);
		return true;
	}

	await mkdir(dirname(path), { recursive: true, mode: 0o700 });
	let current: string | null = null;
	try {
		current = await readFile(path, "utf8");
	} catch (error) {
		if ((error as { code?: string }).code !== "ENOENT") throw error;
	}
	if (current === RELOAD_COMMAND_EXTENSION) return false;
	if (current !== null && !current.includes(MARKER)) {
		throw new Error(`Refusing to overwrite ${path}: it was not generated by paseo-pi`);
	}
	await writeFile(path, RELOAD_COMMAND_EXTENSION, { encoding: "utf8", mode: 0o600 });
	await chmod(path, 0o600);
	return true;
}
